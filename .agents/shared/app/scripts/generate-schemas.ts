import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { jsonSchemaToZod } from "json-schema-to-zod";

// Zod for Astro's content collections, generated from the JSON Schema that the skills emit from their Effect schemas:
// one source of truth, never edited by hand. The analysis's payloads are always read; a plan's only when PLAN_DIR names
// the folder that holds it (`.modernization-backlog/` and `work-items/`).
const dir = process.env.ANALYSIS_PAYLOADS_DIR;
if (dir === undefined || dir === "") {
    throw new Error("ANALYSIS_PAYLOADS_DIR is not set: run this through a skill's build-app command");
}
const planDir = process.env.PLAN_DIR ?? "";
mkdirSync("src/generated", { recursive: true });

/**
 * Write the Zod schema of one JSON Schema file into src/generated.
 * @param name the name of the generated module and its schema (`<name>Schema`)
 * @param file the JSON Schema file
 */
const generate = (name: string, file: string) => {
    const schema: unknown = JSON.parse(readFileSync(file, "utf8"));
    const code = jsonSchemaToZod(schema as never, { module: "esm", name: `${name}Schema`, type: false });
    writeFileSync(`src/generated/${name}.ts`, `// Generated by scripts/generate-schemas.ts. Do not edit.\n${code}`);
};

for (const kind of ["system", "capability", "knowledge", "bundle"]) {
    generate(kind, `${dir}/schema/${kind}.schema.json`);
}
if (planDir === "") {
    // Nothing reads these without a plan, but the content config imports them, so they exist.
    for (const kind of ["plan", "ledger"]) {
        writeFileSync(
            `src/generated/${kind}.ts`,
            `// Generated by scripts/generate-schemas.ts. Do not edit.\nimport { z } from "zod";\nexport const ${kind}Schema = z.never();\n`,
        );
    }
} else {
    const schemas = `${planDir}/.modernization-backlog/payloads/schema`;
    for (const kind of ["plan", "ledger"]) {
        if (!existsSync(`${schemas}/${kind}.schema.json`)) {
            throw new Error(
                `${schemas}/${kind}.schema.json is missing: run the plan skill's write-schemas for ${planDir}`,
            );
        }
        generate(kind, `${schemas}/${kind}.schema.json`);
    }
}
console.log("schemas generated from", dir, planDir === "" ? "" : `and ${planDir}`);
