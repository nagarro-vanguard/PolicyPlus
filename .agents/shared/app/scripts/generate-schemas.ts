import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { jsonSchemaToZod } from "json-schema-to-zod";
import { z } from "zod";
import { sourcesOf } from "../src/case/sources";

// The app's content collections, generated from compose's contract (compose/contract.ts), the one source of truth for
// what `case/` holds: each schema is the contract's own, turned into JSON Schema and back into Zod code, so the
// collections are typed and cannot drift from what compose checks before it writes. Never edited by hand; a test fails
// when this file and the contract disagree.
//
// One collection per facts file (`facts/<name>.json` is the collection `<name>`), one `nodes` collection over every
// `nodes/<level>.json`, and the case's other files the pages read today. A file that is an array gives one entry per
// record, keyed by its first key field; a file that is one object gives one entry named after the collection.

/** Keys that point at other nodes: Astro's `reference()` names them, and the loader's own check fails on a broken one. */
const nodeReferences = `.extend({ up: reference("nodes").nullable(), prev: reference("nodes").nullable(), next: reference("nodes").nullable(), crumbs: z.array(reference("nodes")) })`;

/**
 * The generated module's text.
 * @returns the TypeScript source of src/generated/collections.ts
 */
export const generatedText = (): string => {
    const lines = sourcesOf().map(({ name, files, id, schema }) => {
        const code = jsonSchemaToZod(z.toJSONSchema(schema) as never, { module: "none" });
        const typed = name === "nodes" ? `${code}${nodeReferences}` : code;
        return `    ${name}: defineCollection({\n        loader: caseLoader(${JSON.stringify(name)}, ${JSON.stringify(files)}, ${JSON.stringify(id)}),\n        schema: ${typed},\n    }),`;
    });
    return [
        "// Generated by scripts/generate-schemas.ts from compose/contract.ts. Do not edit.",
        'import { defineCollection, reference } from "astro:content";',
        'import { z } from "zod";',
        'import { caseLoader } from "../case/loader";',
        "",
        "export const collections = {",
        ...lines,
        "};",
        "",
    ].join("\n");
};

if (import.meta.main) {
    const folder = join(import.meta.dir, "..", "src", "generated");
    mkdirSync(folder, { recursive: true });
    writeFileSync(join(folder, "collections.ts"), generatedText());
    console.log(`collections generated from compose/contract.ts: ${sourcesOf().length}`);
}
