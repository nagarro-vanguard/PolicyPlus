import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { jsonSchemaToZod } from "json-schema-to-zod";

// Zod for Astro's content collections, generated from the JSON Schema that write-payloads emits from the Effect schemas:
// one source of truth, never edited by hand.
const dir = process.env.PAYLOADS_DIR;
if (dir === undefined || dir === "") {
    throw new Error("PAYLOADS_DIR is not set: run this through cli/build-ux-visuals.ts");
}
mkdirSync("src/generated", { recursive: true });
for (const kind of ["system", "capability"]) {
    const schema: unknown = JSON.parse(readFileSync(`${dir}/schema/${kind}.schema.json`, "utf8"));
    const code = jsonSchemaToZod(schema as never, { module: "esm", name: `${kind}Schema`, type: false });
    writeFileSync(`src/generated/${kind}.ts`, `// Generated by scripts/generate-schemas.ts. Do not edit.\n${code}`);
}
console.log("schemas generated from", dir);
