import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "@effect/vitest";
import { Effect } from "effect";
import { applyCode, applyTests } from "../core/apply";
import { headCommit } from "../core/git";
import { runPhase } from "../core/layer-checks";
import { writeFiles } from "./support/codebase-fixture";
import { run } from "./support/fixtures";
import { plannedRun } from "./support/planned-run";

const lockfile = "apps/api/bun.lock";

/** A code layer whose check passes, so a plan that changes its manifest can be applied. */
const api = {
    "apps/api/AGENTS.md": "# api\n\n## Owns\n\nRuns.\n\n## Verify\n\n- `echo api`\n",
    "apps/api/package.json": '{"dependencies": {}}\n',
    "apps/api/bun.lock": "old\n",
};

/**
 * A planned run that changes the api manifest and records the lockfile as generated by a command.
 * @param command the command recorded for the lockfile
 * @param layerFiles files that make the codebase's layers, written over the defaults
 * @returns the codebase root and the run's layout
 */
const lockfileRun = (command: string, layerFiles: Record<string, string> = api) =>
    Effect.gen(function* () {
        const { root, layout } = yield* plannedRun(layerFiles, "feature", []);
        writeFiles(root, {
            [`${layout.changes.files.slice(root.length + 1)}/apps/api/package.json`]:
                '{"dependencies": {"x": "1.0.0"}}\n',
        });
        const records = readFileSync(layout.changes.records, "utf8");
        const more = [
            {
                type: "ChangedFile",
                id: "change-2",
                path: "apps/api/package.json",
                action: "modify",
                steps: ["step-1"],
                reason: "r",
            },
            {
                type: "ChangedFile",
                id: "change-3",
                path: lockfile,
                action: "generate",
                command,
                steps: ["step-1"],
                reason: "r",
            },
        ];
        writeFiles(root, {
            [layout.changes.records.slice(root.length + 1)]: [
                records,
                ...more.map((record) => JSON.stringify(record)),
            ].join("\n"),
        });
        return { root, layout };
    });

describe("applying a plan that records a generated file", () => {
    it.effect("leaves the plan's files written and pending, committing nothing, and resumes from that", () =>
        Effect.gen(function* () {
            const { root, layout, commit } = yield* Effect.gen(function* () {
                const planned = yield* lockfileRun("sh -c 'echo broke; exit 4'");
                return { ...planned, commit: yield* run(headCommit(planned.root)) };
            });
            yield* run(applyTests(layout.root));
            yield* run(runPhase(layout.root, "afterTests"));
            const first = yield* run(applyCode(layout.root));
            expect(first.outcome).toBe("pending");
            expect(first.said).toContain("exited 4");
            expect(yield* run(headCommit(root))).toBe(commit);
            expect(readFileSync(join(root, "apps/api/package.json"), "utf8")).toContain('"x": "1.0.0"');
            expect(yield* run(applyCode(layout.root))).toEqual(first);
        }),
    );
});
